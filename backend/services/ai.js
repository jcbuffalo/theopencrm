// AI service — wraps Anthropic's Claude API for in-app assist features.
//
// Designed to fail gracefully:
//   • If ANTHROPIC_API_KEY is not set, calls return { configured: false, ... }
//     and the caller surfaces a "configure your API key" message rather than
//     a 500. This means the AI buttons can ship even when the operator hasn't
//     wired up keys yet.
//
// LIABILITY: Output is generated by a third-party LLM. The operator is
// responsible for reviewing every AI-drafted email, summary, or action item
// before sending or relying on it.

const logger = require('./logger');
const usageMeter = require('./usageMeter');
const aiMetering = require('./aiMetering');
const quotaEnforcer = require('./quotaEnforcer');
const aiModel = require('./aiModel');
const orgAiKeys = require('./orgAiKeys');

// Deployment-wide platform key. Read per call (was a module-load capture)
// so ops key rotation — and env-staged tests — don't need a fresh require;
// existing suites that set the var before the first require are unaffected.
// Per-org bring-your-own keys (migration 153) are resolved per call by
// resolveApiKey() and take precedence.
function platformApiKey() {
  return process.env.ANTHROPIC_API_KEY;
}
const ENDPOINT = 'https://api.anthropic.com/v1/messages';

// ---------------------------------------------------------------------------
// AI Gateway (spec 202) — self-host fallback.
// A self-hosted instance with no org BYO key and no platform ANTHROPIC_API_KEY
// can set OPENCRM_AI_GATEWAY_KEY (an ocrm_gw_* key minted on the hosted
// platform's /settings#billing page). Calls then go to the hosted metered
// proxy instead of Anthropic directly; the hosted org pays for the usage.
//
// URL JOIN: the gateway base URL is joined with '/v1/messages' — exactly the
// join the Anthropic Node SDK performs on a custom baseURL (client.messages
// .create → POST `${baseURL}/v1/messages`) — so the default base
// https://app.theopencrm.com/api/gateway resolves to the proxy mount
// /api/gateway/v1/messages verbatim. gatewayMessagesUrl() is exported and
// unit-tested to keep that join honest. Env is read per call (not captured
// at load) so key rotation doesn't need a restart.
const DEFAULT_GATEWAY_URL = 'https://app.theopencrm.com/api/gateway';
function gatewayBaseUrl() {
  return (process.env.OPENCRM_AI_GATEWAY_URL || DEFAULT_GATEWAY_URL).replace(/\/+$/, '');
}
function gatewayMessagesUrl() {
  return `${gatewayBaseUrl()}/v1/messages`;
}
function gatewayKeyConfigured() {
  return !!process.env.OPENCRM_AI_GATEWAY_KEY;
}

// Per-call resolver — replaces the module-level MODEL constant. The actual
// model + effort is now per-org configurable (services/aiModel.js) with a
// fallback chain ending at 'claude-sonnet-4-6'. Callers pass orgId; lookups
// hit a 30s in-process cache, so the hot path is cheap.
async function resolveAiSettings(orgId) {
  return aiModel.getOrgAiSettings(orgId);
}

/**
 * Resolve which key a call should go out under, and how it is billed.
 *   { key, billingMode: 'byo_key' }  — the org stored its own Anthropic key
 *   { key, billingMode: 'platform' } — the deployment ANTHROPIC_API_KEY
 *   { key, billingMode: 'gateway', endpoint } — OPENCRM_AI_GATEWAY_KEY (spec
 *       202): the self-host fallback; calls go to the hosted metered proxy
 *       at `endpoint` and the hosted org pays for the usage.
 *   null                             — none exist (AI not configured)
 * The org key wins when both exist: the customer opted to pay Anthropic
 * directly, so we must not burn (and upcharge) the platform key instead.
 * The gateway key is last: an instance with its own ANTHROPIC_API_KEY has
 * no reason to pay the gateway's 2× upcharge.
 */
async function resolveApiKey(orgId = null) {
  if (orgId) {
    const orgKey = await orgAiKeys.getOrgKey(orgId);
    if (orgKey) return { key: orgKey, billingMode: 'byo_key' };
  }
  const platformKey = platformApiKey();
  if (platformKey) return { key: platformKey, billingMode: 'platform' };
  if (gatewayKeyConfigured()) {
    return {
      key: process.env.OPENCRM_AI_GATEWAY_KEY,
      billingMode: 'gateway',
      endpoint: gatewayMessagesUrl(),
    };
  }
  return null;
}

/**
 * Sync capability check. True when the platform key exists, or when the
 * org's BYO key is already in the in-process cache (a cold cache answers
 * from the platform key only — use isConfiguredForOrg for the async truth).
 * Callers that pass no orgId keep the historical "platform key present"
 * semantics.
 */
function isConfigured(orgId = null) {
  return !!platformApiKey() || gatewayKeyConfigured() || orgAiKeys.hasKeyCached(orgId);
}

/** Async form: platform key OR a stored (decryptable) BYO key for the org. */
async function isConfiguredForOrg(orgId = null) {
  return (await resolveApiKey(orgId)) !== null;
}

/**
 * Call Claude. When `orgId` is provided, increments usage_meter for the
 * org (ai_requests + ai_input_tokens + ai_output_tokens + cost estimate).
 * Callers in route handlers should pass `orgId: req.orgId` so platform AI
 * usage gets counted against the right tenant for billing (Phase F).
 *
 * Additionally writes a per-call row to ai_usage_events (migration 080)
 * via services/aiMetering.recordUsage when orgId is set. This is the
 * canonical ledger for per-user / per-endpoint cost attribution and the
 * future Stripe meter push (services/aiBilling.js). The usageMeter
 * aggregate is kept in parallel for backward compat with quotaEnforcer.
 *
 * @param {object} opts
 * @param {string} opts.system - system prompt
 * @param {array}  opts.messages - Anthropic-format messages array
 * @param {number} [opts.maxTokens=1024]
 * @param {number} [opts.orgId]    - if provided, usage is recorded against this org
 * @param {number} [opts.userId]   - if provided, attributed in ai_usage_events for per-user breakdown
 * @param {string} [opts.endpoint] - short label for the ai_usage_events row ("summarize-deal", "draft-followup", etc.)
 */
async function callClaude({ system, messages, maxTokens = 1024, orgId = null, userId = null, endpoint = 'callClaude' }) {
  const creds = await resolveApiKey(orgId);
  if (!creds) {
    return { configured: false, message: 'AI not configured. Set ANTHROPIC_API_KEY on the backend or add your own Anthropic key under Usage.' };
  }
  // Quota check BEFORE we burn a Claude call. Throws QuotaExceeded on
  // overrun for the free tier (no overage); paid tiers log the overage but
  // proceed (billing layer reconciles monthly). Fail-open on any internal
  // error so a meter outage doesn't take AI offline.
  if (orgId || userId) {
    try {
      const seats = orgId ? await quotaEnforcer.getSeatCount(orgId) : 1;
      await quotaEnforcer.checkAiQuota({ orgId, userId, userCount: seats });
    } catch (err) {
      if (err instanceof quotaEnforcer.QuotaExceeded) {
        return {
          configured: true,
          ok: false,
          error: err.message,
          code: 'QUOTA_EXCEEDED',
          details: err.details,
        };
      }
      // any other error → fail-open
    }
  }
  // Resolve { model, effort } per-org. Fail-safe inside aiModel returns
  // defaults on lookup failure, so this never throws.
  const { model, effort } = await resolveAiSettings(orgId);
  const thinkingBudget = aiModel.effortToThinkingBudget(effort);
  try {
    const body = {
      model,
      // max_tokens must exceed thinking.budget_tokens (Anthropic counts thinking
      // within max_tokens). Add the budget on top of the caller's output budget.
      max_tokens: maxTokens + (thinkingBudget || 0),
      system,
      messages,
    };
    if (thinkingBudget !== null) {
      body.thinking = { type: 'enabled', budget_tokens: thinkingBudget };
    }
    // Gateway mode (spec 202): same Messages API dialect, different URL +
    // the ocrm_gw_ key as a Bearer credential (the proxy also accepts it in
    // x-api-key, which we send regardless — that keeps the header shape
    // identical to a direct Anthropic call). NOTE: named apiUrl, NOT
    // `endpoint` — `endpoint` is this function's metering label parameter.
    const apiUrl = creds.endpoint || ENDPOINT;
    const headers = {
      'x-api-key': creds.key,
      'anthropic-version': '2023-06-01',
      'content-type': 'application/json',
    };
    if (creds.billingMode === 'gateway') {
      headers['authorization'] = `Bearer ${creds.key}`;
    }
    const res = await fetch(apiUrl, {
      method: 'POST',
      headers,
      body: JSON.stringify(body),
    });
    if (!res.ok) {
      const text = await res.text();
      logger.warn('ai_api_error', { status: res.status, body: text.slice(0, 500) });
      // Failed calls still count as an attempted request for rate-limit/abuse
      // tracking, but don't accrue token cost.
      if (orgId) await usageMeter.increment(orgId, 'ai_requests', 1, 0).catch(() => {});
      return { configured: true, ok: false, error: `API error ${res.status}` };
    }
    const json = await res.json();
    const text = (json.content || []).map(b => b.text || '').join('').trim();
    // Record usage. Anthropic returns `usage: { input_tokens, output_tokens,
    // cache_creation_input_tokens?, cache_read_input_tokens? }`.
    // We write two ledgers:
    //   1. usage_meter (aggregate per org/period) — kept for quotaEnforcer
    //   2. ai_usage_events (per-call row) — feeds /usage breakdown + Stripe meter
    if (orgId && json.usage) {
      await usageMeter.recordAiUsage(orgId, {
        inputTokens:  json.usage.input_tokens || 0,
        outputTokens: json.usage.output_tokens || 0,
      }).catch(() => {});
      // Fire-and-forget: aiMetering.recordUsage swallows its own errors so
      // a metering hiccup never breaks the user-facing AI request.
      // We record the model that actually ran, which is the per-org-resolved
      // id — keeps ai_usage_events.model honest for the billing pipeline.
      aiMetering.recordUsage({
        orgId,
        userId,
        endpoint,
        model,
        usage: json.usage,
        billingMode: creds.billingMode,
      });
    }
    // Surface the model that actually ran so callers like intelSummary /
    // gmailSummary can persist it on their summary rows without a second
    // aiModel lookup. Keeps test fixtures simpler and avoids an extra
    // pool.query when the cache is cold.
    return { configured: true, ok: true, text, usage: json.usage, model, billing_mode: creds.billingMode };
  } catch (err) {
    logger.error('ai_call_failed', { error: err.message });
    return { configured: true, ok: false, error: err.message };
  }
}

/**
 * Build a structured deal summary the operator can paste into a status update.
 */
async function summarizeDeal({ deal, vendorQuotes = [], issues = [], lastActivities = [], orgId = null, userId = null }) {
  const factSheet = [
    `Deal: ${deal.title}`,
    `Stage: ${deal.stage} (phase: ${deal.phase})`,
    `Customer: ${deal.customer_name || deal.company_name || 'unknown'}`,
    `Vendor: ${deal.vendor_name || 'none'}`,
    `Amount: ${deal.amount ? `$${Number(deal.amount).toLocaleString()}` : 'unset'}`,
    `Expected close: ${deal.expected_close_date || 'unset'}`,
    deal.notes ? `Notes: ${deal.notes}` : null,
    vendorQuotes.length > 0
      ? `Vendor quotes: ${vendorQuotes.map(v => `${v.vendor_name || '?'} ${v.amount ? `$${v.amount}` : '(no quote)'}${v.is_selected ? ' SELECTED' : ''}`).join(' · ')}`
      : null,
    issues.length > 0
      ? `Open issues: ${issues.map(i => `[${i.urgency}] ${i.title}`).join(' · ')}`
      : null,
    lastActivities.length > 0
      ? `Recent activity: ${lastActivities.slice(0, 5).map(a => `${a.type} on ${new Date(a.activity_date).toLocaleDateString()} — ${a.title}`).join(' / ')}`
      : null,
  ].filter(Boolean).join('\n');

  return callClaude({
    system: 'You are a concise sales operations assistant. Produce a 4-6 sentence executive summary of the deal\'s current state and the single most important next action. Use plain prose, no bullet points unless absolutely necessary. Never invent facts not in the input.',
    messages: [{ role: 'user', content: `Here is the current deal state:\n\n${factSheet}\n\nWrite the summary.` }],
    maxTokens: 400,
    orgId,
    userId,
    endpoint: 'summarize-deal',
  });
}

/**
 * Draft a follow-up email to a customer or vendor based on deal context.
 */
async function draftFollowUp({ deal, recipient = 'customer', tone = 'professional', customNote = '', orgId = null, userId = null }) {
  const factSheet = [
    `Deal: ${deal.title}`,
    `Stage: ${deal.stage}`,
    `Recipient: ${recipient === 'vendor' ? `vendor (${deal.vendor_name || 'unknown'})` : `customer (${deal.customer_name || 'unknown'})`}`,
    `Amount: ${deal.amount ? `$${Number(deal.amount).toLocaleString()}` : 'unset'}`,
    deal.notes ? `Context: ${deal.notes}` : null,
    customNote ? `Operator's instruction: ${customNote}` : null,
  ].filter(Boolean).join('\n');

  return callClaude({
    system: `You are a sales correspondence assistant. Draft a brief, ${tone} follow-up email. Output ONLY the email body in plain text — no subject line, no greeting placeholder like [Name]. Use real-sounding placeholders like [first name] only when needed. Keep it under 150 words. Never invent commercial terms not given.`,
    messages: [{ role: 'user', content: `Deal context:\n\n${factSheet}\n\nDraft the email.` }],
    maxTokens: 500,
    orgId,
    userId,
    endpoint: 'draft-followup',
  });
}

// ============================================================================
// CONVERSATIONAL SEARCH (Differentiation Bet #3 — see COMPETITIVE_REVIEW.md)
// ============================================================================
// Turns a natural-language query ("show me deals over $50K from CA with no
// activity in 30 days") into a structured filter spec the existing list
// endpoints can consume. The route handler validates filter keys against a
// per-resource allowlist before trusting them. The model never sees customer
// data — only the schema + the user's free-text query.

// Filter-key allowlist per resource. Each key is documented with what the
// frontend will do with it; the route handler rejects any key not in this
// list. Date keys accept either an ISO date string (YYYY-MM-DD) or a relative
// "N days ago" descriptor — the frontend resolves both to filter state.
const SEARCH_CATALOG = {
  deals: {
    description: 'Sales opportunities. Has amount, stage, phase, expected_close_date, hot_flag, last_activity_at.',
    filters: {
      stage:          'string — one of TRIAGE, VENDOR_QUOTING, CUSTOMER_QUOTING, FOLLOW_UP, NO_FOLLOW_UP, NO_QUOTE, LOST, COLD, CANCELLED, NOT_PROCESSED, PROCESSED, ORDACK, VAP, CAP, RELACK, MONITOR, COORDINATE, WHSE, TBI, COMM_WATCH, INVOICED, CLOSED_PAID, CLOSED, SERVICE, CLOSEOUTS, CUSTOMER_EXPERIENCE, WARRANTY, MARKETING, END_USER, lead, qualified, proposal, negotiation, closed_won, closed_lost',
      phase:          'string — one of pre_sale, post_sale, post_ship',
      hot:            'boolean — only HOT-flagged deals',
      search:         'string — substring match on title or PO number',
      amount_min:     'number — minimum deal amount (USD)',
      amount_max:     'number — maximum deal amount (USD)',
      last_activity_window: 'string — one of "30d","60d","90d","180d","never" (deals with no activity in that window or ever)',
      overdue:        'boolean — expected_close_date passed and deal not yet closed',
      new_customer_only:     'boolean — customer first_deal_at within last 90 days',
      dormant_customer_only: 'boolean — customer has no deal in last 180 days',
    },
    sortFields: ['amount', 'expected_close_date', 'created_at', 'last_activity_at'],
  },
  contacts: {
    description: 'People at companies. Has first_name, last_name, email, job_title, status.',
    filters: {
      status: 'string — one of prospect, customer, lead, inactive',
      search: 'string — substring match on first_name, last_name, or email',
    },
    sortFields: ['created_at', 'last_name'],
  },
  companies: {
    description: 'Customer / vendor / partner organizations. Has name, type, industry, status, location.',
    filters: {
      type:     'string — one of customer, vendor, end_user, partner, other',
      status:   'string — one of active, inactive, lead',
      industry: 'string — free-form industry name',
      search:   'string — substring match on company name or website',
    },
    sortFields: ['created_at', 'name'],
  },
  tasks: {
    description: 'To-do items. Has title, status, priority, due_date, optional contact_id/deal_id link.',
    filters: {
      bucket: 'string — one of open, in_progress, done, overdue, all (the page-level bucket selector)',
    },
    sortFields: ['due_date', 'created_at'],
  },
};

function buildSearchSystemPrompt({ today, hint }) {
  // The catalog is rendered into the prompt so the model only sees the
  // filter keys it's allowed to emit. Anything else the user asks for ("show
  // me deals tagged with red-flag") returns a normal filter set with the
  // tagged constraint dropped — the explanation should call this out.
  const catalogText = Object.entries(SEARCH_CATALOG).map(([resource, spec]) => {
    const filters = Object.entries(spec.filters)
      .map(([k, v]) => `    • ${k}: ${v}`)
      .join('\n');
    return `RESOURCE "${resource}" — ${spec.description}\n  Allowed filter keys:\n${filters}\n  Allowed sort fields: ${spec.sortFields.join(', ')}`;
  }).join('\n\n');

  return `You convert a user's natural-language CRM search into a strict JSON filter spec.

Today's date is ${today}. When the user asks for relative dates ("last 30 days", "this quarter"), resolve them against this date.

Available resources and the EXACT filter keys you may emit per resource:

${catalogText}

${hint ? `The caller has pre-selected resource="${hint}". Use that resource unless the query is clearly about a different one.` : 'If the resource is ambiguous, pick the best fit based on the entity being filtered.'}

OUTPUT CONTRACT — your reply MUST be a single JSON object, no prose, no markdown fence, with exactly these keys:
{
  "resource":    "deals" | "contacts" | "companies" | "tasks",
  "filter":      { ...only keys from the allowed list for the chosen resource... },
  "sort":        { "field": <one of the resource's sortFields>, "direction": "asc"|"desc" } | null,
  "explanation": "one short sentence explaining the filters you picked, plain English"
}

Rules:
- NEVER invent filter keys. If the user asks for something you can't express, omit it and mention the omission in the explanation.
- Numbers must be unquoted JSON numbers ($50K → 50000).
- Booleans must be unquoted true/false.
- Dates must be YYYY-MM-DD ISO strings.
- If the user describes "no activity in N days", use last_activity_window with the closest matching bucket ("30d","60d","90d","180d"). Otherwise omit it.
- Reply with ONLY the JSON. No preamble, no closing remarks, no code fence.`;
}

/**
 * Convert a natural-language search query into a filter spec.
 *
 * @param {object} opts
 * @param {string} opts.query        - the user's free-text query
 * @param {string} [opts.resource]   - optional hint: deals|contacts|companies|tasks
 * @param {number} [opts.orgId]      - for usage metering
 */
async function conversationalSearch({ query, resource, orgId = null, userId = null }) {
  const today = new Date().toISOString().slice(0, 10);
  const system = buildSearchSystemPrompt({ today, hint: resource });
  const result = await callClaude({
    system,
    messages: [{ role: 'user', content: query }],
    maxTokens: 600,
    orgId,
    userId,
    endpoint: 'conversational-search',
  });
  if (!result.ok) return result;

  // Parse + clean. The prompt asks for raw JSON, but defend against the
  // model wrapping it in a ```json fence anyway — strip a leading fence
  // line and a trailing one before parsing.
  let raw = (result.text || '').trim();
  if (raw.startsWith('```')) {
    raw = raw.replace(/^```(?:json)?\s*/i, '').replace(/```\s*$/i, '').trim();
  }
  // Also handle leading prose before the JSON object — find the first '{'
  // and last '}' and parse that slice.
  const first = raw.indexOf('{');
  const last  = raw.lastIndexOf('}');
  if (first === -1 || last === -1 || last <= first) {
    return { configured: true, ok: false, error: 'Model returned no JSON', rawText: result.text };
  }
  let parsed;
  try {
    parsed = JSON.parse(raw.slice(first, last + 1));
  } catch (err) {
    return { configured: true, ok: false, error: 'Model returned malformed JSON: ' + err.message, rawText: result.text };
  }
  return { configured: true, ok: true, spec: parsed, usage: result.usage };
}

