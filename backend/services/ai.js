// ---------------------------------------------------------------------------
// Streaming support for runChatTurn
//
// When the caller passes `onEvent`, every Messages API call in the tool loop
// is made with `stream: true` and consumed as Server-Sent Events. The content
// blocks are reconstructed from the deltas so the loop can echo the assistant
// turn back verbatim (thinking blocks + signatures included — Anthropic
// rejects a tool-use continuation whose thinking blocks were dropped).
//
// What the caller sees, in order, per turn:
//   { type: 'status', tool, text }  — a tool call started (human label below)
//   { type: 'token',  text }        — an assistant text delta
//   { type: 'reset',  text }        — the text streamed so far in THIS model
//                                     message was a pre-tool preamble ("Let me
//                                     check…"), not the reply; the caller
//                                     should retract it (we hand it back so a
//                                     UI can keep it as a muted note). Keeps
//                                     the streamed text equal to the final
