function toolStatusLabel(name) {
  if (TOOL_STATUS_LABELS[name]) return TOOL_STATUS_LABELS[name];
  const n = String(name || '');
  const words = (s) => s.replace(/_/g, ' ');
  if (n.startsWith('propose_')) return 'Preparing a change for you to confirm…';
  if (n.startsWith('list_'))    return `Looking at ${words(n.slice(5))}…`;
  if (n.startsWith('get_'))     return `Pulling up ${words(n.slice(4))}…`;
  return n ? `Working on ${words(n)}…` : 'Working…';
}

// Iterate a fetch Response body regardless of its concrete shape: a web
// ReadableStream (Node 18+ undici), a Node stream / async iterable (tests,
// older polyfills), or a single string / byte chunk.
async function* iterateBody(body) {
  if (!body) return;
  if (typeof body.getReader === 'function') {
    const reader = body.getReader();
    try {
      for (;;) {
        const { done, value } = await reader.read();
        if (done) return;
        yield value;
      }
    } finally {
      try { reader.releaseLock(); } catch { /* already released */ }
    }
    return;
  }
  if (typeof body[Symbol.asyncIterator] === 'function' || typeof body[Symbol.iterator] === 'function') {
    for await (const chunk of body) yield chunk;
    return;
  }
  yield body;
}

// One SSE block ("event: x\ndata: {...}") -> { event, data } or null.
function parseSseBlock(raw) {
  let event = 'message';
  const data = [];
  for (const line of raw.split(/\r?\n/)) {
    if (!line || line.startsWith(':')) continue;
    const i = line.indexOf(':');
    const field = i === -1 ? line : line.slice(0, i);
    let value = i === -1 ? '' : line.slice(i + 1);
    if (value.startsWith(' ')) value = value.slice(1);
    if (field === 'event') event = value;
    else if (field === 'data') data.push(value);
  }
  if (!data.length) return null;
  return { event, data: data.join('\n') };
}

// Async generator over the SSE events in a streamed Messages API response.
async function* readSseEvents(body) {
  const decoder = new TextDecoder();
  let buf = '';
  const SEP = /\r?\n\r?\n/;
  for await (const chunk of iterateBody(body)) {
    buf += typeof chunk === 'string' ? chunk : decoder.decode(chunk, { stream: true });
    let m;
    while ((m = SEP.exec(buf))) {
      const raw = buf.slice(0, m.index);
      buf = buf.slice(m.index + m[0].length);
      const evt = parseSseBlock(raw);
      if (evt) yield evt;
    }
  }
  buf += decoder.decode();
  if (buf.trim()) {
    const evt = parseSseBlock(buf);
    if (evt) yield evt;
  }
}

// Consume one streamed model message. Returns the same { content,
// stop_reason, usage } shape the non-streaming path reads off res.json(),
// emitting status / token / reset events as the deltas arrive. Throws on a
// mid-stream `error` event (with `partialUsage` attached so the caller can
// still meter what Anthropic already billed) or on abort.
async function consumeStreamedMessage(res, { emit, signal }) {
  const blocks = [];
  const partialJson = [];
  let usage = {};
  let stopReason = null;
  // Text streamed so far in this message. Retracted (reset) if a tool_use
  // block follows — that text was a preamble, not the reply.
  let textSoFar = '';

  for await (const { event, data } of readSseEvents(res.body)) {
    if (signal && signal.aborted) {
      throw Object.assign(new Error('Request cancelled'), { name: 'AbortError', partialUsage: usage });
    }
    let payload;
    try { payload = JSON.parse(data); } catch { continue; }
    const type = payload.type || event;
    const idx = payload.index;

    if (type === 'message_start') {
      usage = { ...((payload.message && payload.message.usage) || {}) };
    } else if (type === 'content_block_start') {
      const b = payload.content_block || {};
      if (b.type === 'text') {
        blocks[idx] = { type: 'text', text: b.text || '' };
      } else if (b.type === 'tool_use') {
        blocks[idx] = { type: 'tool_use', id: b.id, name: b.name, input: {} };
        partialJson[idx] = '';
        if (textSoFar) {
          emit({ type: 'reset', text: textSoFar });
          textSoFar = '';
        }
        emit({ type: 'status', tool: b.name, text: toolStatusLabel(b.name) });
      } else if (b.type === 'thinking') {
        blocks[idx] = { type: 'thinking', thinking: b.thinking || '', signature: b.signature || '' };
      } else {
        // redacted_thinking and anything newer: echo verbatim on replay.
        blocks[idx] = { ...b };
      }
    } else if (type === 'content_block_delta') {
      const d = payload.delta || {};
      const blk = blocks[idx];
      if (!blk) continue;
      if (d.type === 'text_delta') {
        const t = d.text || '';
        blk.text = (blk.text || '') + t;
        textSoFar += t;
        if (t) emit({ type: 'token', text: t });
      } else if (d.type === 'input_json_delta') {
        partialJson[idx] = (partialJson[idx] || '') + (d.partial_json || '');
      } else if (d.type === 'thinking_delta') {
        blk.thinking = (blk.thinking || '') + (d.thinking || '');
      } else if (d.type === 'signature_delta') {
        blk.signature = (blk.signature || '') + (d.signature || '');
      }
    } else if (type === 'content_block_stop') {
      const blk = blocks[idx];
      if (blk && blk.type === 'tool_use') {
        const raw = partialJson[idx];
        if (raw && raw.trim()) {
          try { blk.input = JSON.parse(raw); } catch { blk.input = {}; }
        }
      }
    } else if (type === 'message_delta') {
      if (payload.delta && payload.delta.stop_reason) stopReason = payload.delta.stop_reason;
      if (payload.usage) usage = { ...usage, ...payload.usage };
    } else if (type === 'error') {
      const msg = (payload.error && payload.error.message) || 'stream error';
      throw Object.assign(new Error(msg), { partialUsage: usage, streamError: true });
    }
    // message_stop / ping: nothing to do.
  }

  return { content: blocks.filter(Boolean), stop_reason: stopReason, usage };
}

/**
 * Run one chat turn: feed conversation history + user message into Claude
 * with tool-use enabled, execute any tool calls server-side (scoped to
 * orgId), and loop until Claude emits a final text reply or we hit the
 * iteration cap.
 *
 * @param {object} opts
 * @param {string}   opts.userMessage  - the user's new message
 * @param {array}    opts.history      - prior messages [{role,content}]
 * @param {Function} opts.runTool      - async (name, input) => any
 * @param {number}  [opts.orgId]
 * @param {Function} [opts.onEvent]    - streaming callback; when present every
 *                                       model call streams (see the block
 *                                       comment above consumeStreamedMessage)
 * @param {AbortSignal} [opts.signal]  - aborts the in-flight model call (the
 *                                       client went away); resolves with
 *                                       code 'ABORTED'
 * @returns {Promise<{ok, reply, toolCalls, usage}>}
 */
async function runChatTurn({ userMessage, history = [], runTool, orgId = null, userId = null, systemPrompt = null, onEvent = null, signal = null }) {
  // Per-org BYO key wins over the platform key (see resolveApiKey).
  const creds = await resolveApiKey(orgId);
  if (!creds) {
    return { ok: false, error: 'AI not configured', code: 'AI_NOT_CONFIGURED' };
  }
  const streaming = typeof onEvent === 'function';
  // A throwing UI callback must never take the model turn down with it.
  const emit = streaming ? (evt) => { try { onEvent(evt); } catch { /* ignore */ } } : () => {};
  const aborted = () => !!(signal && signal.aborted);
  // Allow the caller to swap in the debug-mode prompt without reaching into
  // module-private state. Falls back to the default chat prompt.
  const effectiveSystem = systemPrompt || CHAT_SYSTEM_PROMPT;

  // Build the Anthropic-format messages array. History is already in
  // {role,content} shape; we append the new user turn.
  const messages = [
    ...history.map(m => ({ role: m.role, content: m.content })),
    { role: 'user', content: userMessage },
  ];

  const collectedToolCalls = [];
  let totalUsage = { input_tokens: 0, output_tokens: 0 };
  let iterations = 0;

  // Prompt caching: the tool definitions + system prompt are identical on
  // every iteration of this loop (and stable across user turns / sessions).
  // Mark them cacheable so iteration 2..N hits Anthropic's cache-read path
  // (10% of input cost) instead of re-paying for the full ~6KB CHAT_TOOLS
  // schema each round-trip. Cache TTL is the SDK default of 5 minutes,
  // which fits comfortably inside a single user's chat session.
  //
  // Cache_control goes on the LAST tool definition in the array (the SDK
  // caches up to and including the marked block) and on the system block
  // (which forces system to be an array of typed text blocks).
  //
  // recordUsage already passes through cache_creation_input_tokens and
  // cache_read_input_tokens from json.usage — see services/aiMetering.js
  // computeCost. Verify in production via the /usage page's cache-read
  // total in the headline cards.
  const cachedTools = CHAT_TOOLS.map((tool, idx) =>
    idx === CHAT_TOOLS.length - 1
      ? { ...tool, cache_control: { type: 'ephemeral' } }
      : tool
  );
  const cachedSystem = [
    { type: 'text', text: effectiveSystem, cache_control: { type: 'ephemeral' } },
  ];

  // Per-org model + effort. Resolved once at the top of the turn so every
  // tool-use iteration inside the loop uses the same model — flipping models
  // mid-turn would break Anthropic's prompt-cache hits.
  const { model, effort } = await resolveAiSettings(orgId);
  const thinkingBudget = aiModel.effortToThinkingBudget(effort);

  while (iterations < MAX_TOOL_ITERATIONS) {
    iterations++;

    let res;
    try {
      const reqBody = {
        model,
        // Anthropic counts thinking tokens *inside* max_tokens, and requires
        // max_tokens > thinking.budget_tokens. Add the budget on top of the
        // 1024-token output allowance so medium/high effort doesn't 400.
        max_tokens: 1024 + (thinkingBudget || 0),
        system: cachedSystem,
        tools: cachedTools,
        messages,
      };
      if (thinkingBudget !== null) {
        reqBody.thinking = { type: 'enabled', budget_tokens: thinkingBudget };
      }
      // Streaming callers get every iteration streamed (not just the final
      // text turn) — we can't know up front which model message is the last
      // one, and streaming the tool-use turns is what makes the `status`
      // events arrive as the tool call starts rather than after it ran.
      if (streaming) reqBody.stream = true;
      res = await fetch(ENDPOINT, {
        method: 'POST',
        headers: {
          'x-api-key': creds.key,
          'anthropic-version': '2023-06-01',
          'content-type': 'application/json',
        },
        body: JSON.stringify(reqBody),
        ...(signal ? { signal } : {}),
      });
    } catch (err) {
      if (aborted()) {
        return { ok: false, error: 'Request cancelled', code: 'ABORTED', toolCalls: collectedToolCalls, usage: totalUsage };
      }
      logger.error('ai_chat_network_error', { error: err.message });
      return { ok: false, error: err.message, code: 'AI_NETWORK_ERROR' };
    }

    if (!res.ok) {
      const text = await res.text();
      logger.warn('ai_chat_api_error', { status: res.status, body: text.slice(0, 500) });
      if (orgId) await usageMeter.increment(orgId, 'ai_requests', 1, 0).catch(() => {});
      return { ok: false, error: `API error ${res.status}`, code: 'AI_ERROR' };
    }

    let json;
    if (streaming) {
      try {
        json = await consumeStreamedMessage(res, { emit, signal });
      } catch (err) {
        // Meter whatever Anthropic already billed for the partial message
        // (input tokens land in message_start before any delta).
        const partial = err.partialUsage;
        if (orgId && partial && (partial.input_tokens || partial.output_tokens)) {
          totalUsage.input_tokens  += partial.input_tokens  || 0;
          totalUsage.output_tokens += partial.output_tokens || 0;
          aiMetering.recordUsage({
            orgId, userId,
            endpoint: iterations === 1 ? 'chat' : 'chat-tool-iter',
            model, usage: partial, billingMode: creds.billingMode,
          });
          await usageMeter.recordAiUsage(orgId, {
            inputTokens:  totalUsage.input_tokens,
            outputTokens: totalUsage.output_tokens,
          }).catch(() => {});
        }
        if (aborted() || err.name === 'AbortError') {
          return { ok: false, error: 'Request cancelled', code: 'ABORTED', toolCalls: collectedToolCalls, usage: totalUsage };
        }
        logger.warn('ai_chat_stream_error', { error: err.message, iteration: iterations });
        if (orgId) await usageMeter.increment(orgId, 'ai_requests', 1, 0).catch(() => {});
        return { ok: false, error: err.streamError ? `API error: ${err.message}` : err.message, code: 'AI_ERROR', toolCalls: collectedToolCalls };
      }
    } else {
      json = await res.json();
    }
    if (json.usage) {
      totalUsage.input_tokens  += json.usage.input_tokens  || 0;
      totalUsage.output_tokens += json.usage.output_tokens || 0;
      // Per-iteration ai_usage_events row. The chat tool-use loop makes
      // multiple SDK calls per user turn (once per tool-batch round-trip);
      // recording each separately means the per-turn cost reflects reality
      // and the by_endpoint breakdown shows "chat" with the right call count.
      // We tag the iteration in the endpoint label so a follow-up can tell
      // a tool-use loop apart from a single shot if it ever matters.
      if (orgId) {
        aiMetering.recordUsage({
          orgId,
          userId,
          endpoint: iterations === 1 ? 'chat' : 'chat-tool-iter',
          model,
          usage: json.usage,
          billingMode: creds.billingMode,
        });
      }
    }

    const content = json.content || [];
    const toolUses = content.filter(b => b.type === 'tool_use');

    // No more tool use — collect the final text and return.
    if (toolUses.length === 0 || json.stop_reason !== 'tool_use') {
      const replyText = content.filter(b => b.type === 'text').map(b => b.text || '').join('').trim();
      if (orgId) {
        await usageMeter.recordAiUsage(orgId, {
          inputTokens:  totalUsage.input_tokens,
          outputTokens: totalUsage.output_tokens,
        }).catch(() => {});
      }
      return { ok: true, reply: replyText, toolCalls: collectedToolCalls, usage: totalUsage };
    }

    // Execute every tool call in this turn server-side. The result block
    // (one per tool_use_id) is then echoed back as a user message so
    // Claude can keep going.
    messages.push({ role: 'assistant', content });

    const toolResults = [];
    for (const tu of toolUses) {
      let result;
      try {
        result = await runTool(tu.name, tu.input || {});
      } catch (err) {
        result = { error: err.message || 'tool execution failed' };
      }
      // Capture the result alongside the name+input so buildActionsFromToolCalls
      // (in routes/aiRoutes.js) can mint action chips that reference output
      // fields like the new plugin_runs.id from run_plugin. Existing chip
      // mappings only consult tc.name + tc.input — they keep working unchanged.
      collectedToolCalls.push({ name: tu.name, input: tu.input, result });
      toolResults.push({
        type: 'tool_result',
        tool_use_id: tu.id,
        content: typeof result === 'string' ? result : JSON.stringify(result),
      });
    }
    messages.push({ role: 'user', content: toolResults });
  }

  // Bailout: hit the iteration cap. Report a usable error so the route can
  // surface it.
  logger.warn('ai_chat_max_iterations', { iterations, toolCalls: collectedToolCalls.length });
  if (orgId) {
    await usageMeter.recordAiUsage(orgId, {
      inputTokens:  totalUsage.input_tokens,
      outputTokens: totalUsage.output_tokens,
    }).catch(() => {});
  }
  return {
    ok: false,
    error: 'Chat hit max tool-call iterations without a final reply',
    code: 'MAX_ITERATIONS',
    toolCalls: collectedToolCalls,
  };
}

